import Foundation
import LinglongtaiShared

func runAIWorkDurationChecks(check: (String, Bool) -> Void) {
    let base = Date(timeIntervalSince1970: 1_700_000_000)
    var calendar = Calendar(identifier: .gregorian)
    calendar.timeZone = TimeZone(secondsFromGMT: 0)!
    let a = UUID(), b = UUID()
    func event(_ id: UUID, _ seconds: Double, _ status: AgentTaskStatus, _ name: String = "PreToolUse") -> AgentEvent {
        AgentEvent(type: "upsert", id: id, agent: "Codex", status: status, createdAt: base.addingTimeInterval(seconds), sourceEvent: name, sessionID: id.uuidString)
    }
    var ledger = AIWorkDuration()
    ledger.consume(event(a, 0, .running))
    check("duration: unclosed tail is excluded and marked incomplete", ledger.summary(now: base.addingTimeInterval(10), calendar: calendar).seconds == 0 && ledger.summary(now: base.addingTimeInterval(10), calendar: calendar).incomplete)
    ledger.consume(event(b, 10, .running))
    ledger.consume(event(a, 20, .waiting, "PermissionRequest"))
    ledger.consume(event(b, 30, .completed, "Stop"))
    check("duration: parallel intervals count once", ledger.summary(now: base.addingTimeInterval(30), calendar: calendar).seconds == 30)
    ledger.consume(event(a, 50, .running))
    ledger.consume(event(a, 60, .completed, "Stop"))
    check("duration: waiting for the user is excluded", ledger.summary(now: base.addingTimeInterval(60), calendar: calendar).seconds == 40)
    ledger.consume(event(a, 60, .completed, "Stop"))
    check("duration: duplicate Stop never doubles work", ledger.summary(now: base.addingTimeInterval(60), calendar: calendar).seconds == 40)
    let c = UUID()
    ledger.consume(event(c, 70, .running))
    ledger.consume(event(c, 2000, .completed, "Stop"))
    let missing = ledger.summary(now: base.addingTimeInterval(2000), calendar: calendar)
    check("duration: long unobserved gaps are not guessed", missing.seconds == 40 && missing.incomplete)
    var uncertain = AIWorkDuration()
    uncertain.consume(event(a, 0, .running))
    uncertain.consume(AgentEvent(type: "ambiguous-turn", agent: "Codex", createdAt: base.addingTimeInterval(20), sourceEvent: "PreToolUse", sessionID: a.uuidString))
    uncertain.consume(event(a, 30, .completed, "Stop"))
    check("duration: ambiguous rounds do not accrue", uncertain.summary(now: base.addingTimeInterval(30), calendar: calendar).seconds == 0 && uncertain.summary(now: base.addingTimeInterval(30), calendar: calendar).incomplete)
    let midnight = calendar.startOfDay(for: base).addingTimeInterval(86400)
    var night = AIWorkDuration()
    night.consume(AgentEvent(type: "upsert", id: a, agent: "Claude", status: .running, createdAt: midnight.addingTimeInterval(-10), sourceEvent: "UserPromptSubmit", sessionID: "night"))
    night.consume(AgentEvent(type: "upsert", id: a, agent: "Claude", status: .completed, createdAt: midnight.addingTimeInterval(10), sourceEvent: "Stop", sessionID: "night"))
    check("duration: local midnight clips rather than resets active work", night.summary(now: midnight.addingTimeInterval(20), calendar: calendar).seconds == 10)
    check("duration: next day never inherits yesterday's time", night.summary(now: midnight.addingTimeInterval(86400), calendar: calendar).seconds == 0)
    var delayed = AIWorkDuration()
    delayed.consume(event(a, 0, .running))
    delayed.consume(event(a, 10, .waiting, "PermissionRequest"))
    delayed.consume(event(a, 5, .running))
    delayed.consume(event(a, 100, .completed, "Stop"))
    delayed.consume(event(a, 120, .running))
    delayed.consume(event(a, 200, .completed, "Stop"))
    check("duration: delayed callbacks cannot count waiting or resurrect a terminal round", delayed.summary(now: base.addingTimeInterval(200), calendar: calendar).seconds == 10)
    var ended = AIWorkDuration()
    ended.consume(event(a, 0, .running))
    ended.consume(event(a, 10, .waiting, "PermissionRequest"))
    ended.consume(AgentEvent(type: "end-session", agent: "Codex", createdAt: base.addingTimeInterval(20), sourceEvent: "SessionEnd", sessionID: a.uuidString))
    ended.consume(event(a, 30, .running))
    ended.consume(event(a, 100, .completed, "Stop"))
    check("duration: ended waiting sessions cannot restart from delayed tools", ended.summary(now: base.addingTimeInterval(100), calendar: calendar).seconds == 10)
    var damaged = AIWorkDuration()
    damaged.consume(event(a, 0, .running))
    damaged.discontinuity(at: base.addingTimeInterval(10))
    damaged.consume(event(a, 100, .completed, "Stop"))
    check("duration: damaged journal never bridges unknown waiting time", damaged.summary(now: base.addingTimeInterval(100), calendar: calendar).seconds == 0 && damaged.summary(now: base.addingTimeInterval(100), calendar: calendar).incomplete)
}
